/*题目描述:
给定一个3位整数n，计算：
1.n的各位数字之和；
2.n的各位数字之和的平方；
3.n的各位数字之和的立方；
例如，当这个三位数是 123 时：
各位数字之和为：1+2+3=6；
各位数字之和的平方为：(1+2+3) 2 =(1+2+3)×(1+2+3)=36；
各位数字之和的立方为：(1+2+3) 3 =(1+2+3)×(1+2+3)×(1+2+3)=216。
输入格式
输入只有一行一个三位整数 n。
输出格式
输出共三行，第一行为各位数字之和，第二行为各位数字之和的平方，第三行为各位数字之和的立方。
*/


///*C++版本
#include <iostream>
using namespace std;

int main() {
    int num;
    cin >> num;
    int a = num / 100; //百位
    int b = (num / 10) % 10; //十位 
    int c = num % 10; //个位
    int sum = a + b + c;
    cout << sum << endl;
    cout << sum * sum << endl; 
    cout << sum * sum * sum << endl;
    return 0;
}
//*/

